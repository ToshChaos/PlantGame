"""Procedural audio for Overgrown (T17 music + ambience, T18 SFX). Pure python (no numpy), deterministic.

Usage:  python3 docs/audio/make_audio.py [out_root]      (default: Game/Assets/Audio)
Writes  Music/{music_menu,music_gameplay}.wav, Music/amb_wind.wav (loops) and SFX/<name>[_N].wav (one-shots).
All files are generated by this script (no third-party audio), so there is no licence to log beyond the repo's own.
"""
import math, os, random, struct, sys, wave

SR = 22050
TAU = math.pi * 2
ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "Game", "Assets", "Audio")


def hz(note):  # MIDI note -> Hz
    return 440.0 * 2 ** ((note - 69) / 12)


def buf(seconds):
    return [0.0] * int(seconds * SR)


def write(path, data, peak=0.8):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    m = max(max(data), -min(data), 1e-9)
    g = peak / m
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", int(max(-1, min(1, x * g)) * 32767)) for x in data))
    print("wrote", os.path.relpath(path))


def add(dst, src, at=0.0, gain=1.0, wrap=False):
    i0 = int(at * SR); n = len(dst)
    for i, x in enumerate(src):
        j = i0 + i
        if j >= n:
            if not wrap: break
            j %= n
        dst[j] += x * gain


def env_ad(n, a, d_pow=3.0):
    """attack seconds, then (1-t)^pow decay over the rest"""
    na = max(1, int(a * SR)); out = []
    for i in range(n):
        if i < na: out.append(i / na)
        else: out.append((1 - (i - na) / max(1, n - na)) ** d_pow)
    return out


def tone(freq, dur, a=0.005, decay=3.0, partials=((1, 1.0),), glide=None, vib=0.0):
    n = int(dur * SR); e = env_ad(n, a, decay); out = []; ph = 0.0
    for i in range(n):
        f = freq if glide is None else freq + (glide - freq) * (i / n)
        if vib: f *= 1 + vib * math.sin(TAU * 5 * i / SR)
        ph += TAU * f / SR
        s = 0.0
        for k, amp in partials: s += amp * math.sin(ph * k)
        out.append(s * e[i])
    return out


def bell(freq, dur, gain=1.0):
    n = int(dur * SR); out = [0.0] * n
    for ratio, amp, dec in ((1, 1.0, 1.0), (2.0, 0.45, 1.6), (2.76, 0.25, 2.2), (5.4, 0.1, 3.0)):
        for i in range(n):
            t = i / SR
            out[i] += amp * math.sin(TAU * freq * ratio * t) * math.exp(-t * (2.2 * dec / max(0.3, dur) * 1.4))
    for i in range(min(n, 120)): out[i] *= i / 120
    return [x * gain for x in out]


def pluck(freq, dur):  # harp-ish
    return tone(freq, dur, 0.004, 4.0, ((1, 1.0), (2, 0.35), (3, 0.15), (4, 0.06)))


def noise(dur, rng, lp=0.2, hp=0.0, a=0.003, decay=3.0, level=1.0):
    n = int(dur * SR); e = env_ad(n, a, decay); out = []; y = 0.0; z = 0.0
    for i in range(n):
        x = rng.uniform(-1, 1)
        y += lp * (x - y)        # low-pass
        z += hp * (y - z) if hp else 0.0
        out.append(((y - z) if hp else y) * e[i] * level)
    return out


def chain(parts, gap):
    total = max(at + len(p) / SR for at, p in parts)
    out = buf(total + 0.05)
    for at, p in parts: add(out, p, at)
    return out


