# ------------------------------------------------------------------ music (seamless loops: tails wrap around)
def pad_note(freq, dur, rel=1.2):
    n = int((dur + rel) * SR); out = []
    for i in range(n):
        t = i / SR
        a = min(1, t / 0.9)
        r = 1.0 if t < dur else max(0.0, 1 - (t - dur) / rel)
        trem = 0.85 + 0.15 * math.sin(TAU * 0.35 * t)
        s = math.sin(TAU * freq * t) + math.sin(TAU * freq * 1.0035 * t) * 0.8 + 0.25 * math.sin(TAU * freq * 2 * t)
        out.append(s * a * r * trem)
    return out


def music(name, bpm, chords, bars_per_chord, harp_density, seed, bell_only=False):
    rng = random.Random(seed)
    beat = 60.0 / bpm; bar = beat * 4; chord_len = bar * bars_per_chord
    total = chord_len * len(chords)
    out = buf(total)
    scale = (0, 2, 4, 7, 9)   # major pentatonic
    for ci, (root, notes) in enumerate(chords):
        at = ci * chord_len
        for nt in notes: add(out, pad_note(hz(nt), chord_len), at, 0.16, wrap=True)
        add(out, pad_note(hz(root - 12), chord_len), at, 0.20, wrap=True)
        steps = int(chord_len / (beat / 2))
        for s in range(steps):
            if rng.random() < harp_density:
                deg = rng.choice(scale) + 12 * rng.choice((0, 1, 1))
                nt = root + 12 + deg
                tt = at + s * beat / 2
                add(out, bell(hz(nt), 1.6, 0.5) if bell_only else pluck(hz(nt), 1.8), tt, 0.28, wrap=True)
    write(os.path.join(ROOT, "Music", name + ".wav"), out, 0.55)


