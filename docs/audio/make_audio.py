def _bp(x, f, q=4.0):
    """Resonant band-pass biquad over a list of samples (centre f in Hz)."""
    w0 = TAU * f / SR; al = math.sin(w0) / (2 * q); c = math.cos(w0)
    b0, b2, a0, a1, a2 = al, -al, 1 + al, -2 * c, 1 - al
    y = []; x1 = x2 = y1 = y2 = 0.0
    for v in x:
        o = (b0 * v + b2 * x2 - a1 * y1 - a2 * y2) / a0
        x2, x1, y2, y1 = x1, v, y1, o
        y.append(o)
    return y


def _loop_xfade(out, T, extra):
    m = int(T * SR); x = int(extra * SR); loop = out[:m]
    for i in range(x):
        w = i / x; loop[i] = loop[i] * w + out[m + i] * (1 - w)
    return loop


